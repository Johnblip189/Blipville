"""Copies every pet's pixel art, colors and lines from blip.pyw into go/data.js,
so Blipville: On the Go (the phone version) always matches the desktop app.

    python tools/export_go_data.py
"""
import importlib.util
import json
import os
from importlib.machinery import SourceFileLoader

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
spec = importlib.util.spec_from_loader("blip", SourceFileLoader("blip", os.path.join(ROOT, "blip.pyw")))
bl = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bl)

kinds = {}
for k in bl.KINDS:
    v = bl.VARIANTS[k]
    kinds[k] = {
        "body": v["body"], "alt": v.get("alt"), "eyes": v["eyes"], "mouth": v.get("mouth", True),
        "feet": v["feet"], "dx": v.get("dx", 0), "move": v["move"], "speed": v.get("speed", 1.0),
        "shifty": bool(v.get("shifty")), "extra": v.get("extra", {}),
        "lines": v["lines"], "colors": bl.kind_colors(k),
        "default": bl.default_color(k),
    }
data = {
    "kinds": kinds,
    "groups": {"critters": bl.CRITTERS, "animals": bl.ANIMAL_KINDS, "nightShift": bl.NIGHT_SHIFT, "rare": bl.RARE_KINDS, "cryptids": bl.CRYPTID_KINDS, "kaiju": bl.KAIJU_KINDS, "tabs": bl.TAB_GROUPS, "gifts": bl.GIFT_KINDS, "legends": bl.LEGEND_KINDS},
    "lines": {"idle": bl.LINES_IDLE, "pet": bl.LINES_PET, "held": bl.LINES_HELD, "land": bl.LINES_LAND,
              "eat": bl.LINES_EAT, "wake": bl.LINES_WAKE, "hungry": bl.LINES_HUNGRY},
    "names": bl.NAMES,
    "eggCost": bl.EGG_COST,
    "lureCost": bl.LURE_COST,
    "beaconCost": bl.BEACON_COST,
    "kaijuHits": bl.KAIJU_HITS,
    "giftNow": bl.GIFT_NOW,
    "giftDrops": [{k: d[k] for k in ("kind", "until", "why")} for d in bl.GIFT_DROPS],
    "legendWorld": bl.LEGEND_WORLD,
    "worlds": [{k: w[k] for k in ("name", "icon", "tab", "cost")} for w in bl.WORLDS],
    "giftUntil": bl.GIFT_UNTIL,
    "scenes": bl.SCENES,
    "sceneProps": bl.SCENE_PROPS,
    "sceneSize": [bl.SCENE_W, bl.SCENE_H],
    "unlocks": bl.UNLOCKS,
    "hats": bl.HATS,
    "seasonLines": bl.SEASON_LINES,
}
out = os.path.join(ROOT, "go", "data.js")
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/export_go_data.py from blip.pyw. Don't edit by hand.\n")
    f.write("window.BLIP_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"wrote {out}: {len(kinds)} kinds, {os.path.getsize(out) // 1024} KB")
